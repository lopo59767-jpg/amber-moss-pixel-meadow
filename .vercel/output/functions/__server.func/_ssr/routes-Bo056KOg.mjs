async function fileToRecent(file) {
	const mime = file.type || "application/octet-stream";
	if (mime.startsWith("image/")) {
		const url = await compressImage(file, 1280, .72);
		return {
			name: file.name,
			mime,
			url,
			at: Date.now()
		};
	}
	if (mime.startsWith("text/") || /\.(md|txt|json|csv|js|ts|py|html|css)$/i.test(file.name)) {
		const text = (await file.text()).slice(0, 2e4);
		return {
			name: file.name,
			mime,
			text,
			at: Date.now()
		};
	}
	return {
		name: file.name,
		mime,
		text: `Файл ${file.name} (${Math.ceil(file.size / 1024)} КБ)`,
		at: Date.now()
	};
}
function compressImage(file, max, quality) {
	return new Promise((resolve, reject) => {
		const reader = new FileReader();
		reader.onerror = () => reject(/* @__PURE__ */ new Error("файл"));
		reader.onload = () => {
			const img = new Image();
			img.onload = () => {
				const scale = Math.min(1, max / Math.max(img.width, img.height));
				const canvas = document.createElement("canvas");
				canvas.width = Math.max(1, Math.round(img.width * scale));
				canvas.height = Math.max(1, Math.round(img.height * scale));
				const ctx = canvas.getContext("2d");
				if (!ctx) return reject(/* @__PURE__ */ new Error("canvas"));
				ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
				resolve(canvas.toDataURL("image/jpeg", quality));
			};
			img.onerror = () => reject(/* @__PURE__ */ new Error("image"));
			img.src = String(reader.result);
		};
		reader.readAsDataURL(file);
	});
}
