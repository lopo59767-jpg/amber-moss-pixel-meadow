function filterNews(items, auto) {
	const keys = auto.keyword.split(",").map((s) => s.trim().toLowerCase()).filter(Boolean);
	const sources = auto.sources.split(",").map((s) => s.trim().toLowerCase()).filter(Boolean);
	return items.filter((item) => {
		const blob = `${item.title} ${item.source} ${item.link}`.toLowerCase();
		if (keys.length && !keys.some((k) => blob.includes(k))) return false;
		if (sources.length && !sources.some((s) => blob.includes(s))) return false;
		return true;
	});
}
function tickAutomations() {
	const { automations } = useStudio.getState().data;
	const now = Date.now();
	for (const auto of automations) {
		if (!auto.enabled || auto.paused || auto.status === "running") continue;
		if (auto.preset === "remind") {
			if (auto.reminders.some((r) => r.at <= now)) runAutomation(auto.id);
			continue;
		}
		if ((auto.schedule === "hourly" || auto.schedule === "daily") && auto.nextRun && auto.nextRun <= now) runAutomation(auto.id);
	}
}
