function Rich({ text }) {
	const chunks = [];
	const re = /```[\w-]*\n?([\s\S]*?)```/g;
	let last = 0;
	let match;
	while (match = re.exec(text)) {
		if (match.index > last) chunks.push({
			kind: "text",
			value: text.slice(last, match.index)
		});
		chunks.push({
			kind: "code",
			value: match[1] ?? ""
		});
		last = match.index + match[0].length;
	}
	if (last < text.length) chunks.push({
		kind: "text",
		value: text.slice(last)
	});
	return /* @__PURE__ */ (0, import_jsx_runtime.jsx)("div", {
		className: "space-y-3",
		children: chunks.map((chunk, i) => chunk.kind === "code" ? /* @__PURE__ */ (0, import_jsx_runtime.jsx)("pre", {
			className: "overflow-x-auto rounded-lg bg-bg p-3 font-mono text-sm leading-relaxed text-fg",
			children: /* @__PURE__ */ (0, import_jsx_runtime.jsx)("code", { children: chunk.value.replace(/\n$/, "") })
		}, i) : /* @__PURE__ */ (0, import_jsx_runtime.jsx)("p", {
			className: "whitespace-pre-wrap leading-relaxed",
			children: chunk.value
		}, i))
	});
}
