	async function attach(file) {
		if (!file) return;
		try {
			const item = await fileToRecent(file);
			mutate((d) => {
				d.recent.unshift({
					id: uid("file"),
					...item
				});
				d.recent = d.recent.slice(0, 8);
				if (item.url && item.mime.startsWith("image/")) d.library.unshift({
					id: uid("lib"),
					kind: "media",
					mediaType: "image",
					title: item.name,
					url: item.url,
					at: Date.now(),
					icon: "square",
					color: "#f4f4f5"
				});
				else if (item.text) d.library.unshift({
					id: uid("lib"),
					kind: "file",
					title: item.name,
					text: item.text,
					at: Date.now(),
					icon: "square",
					color: "#a1a1aa"
				});
			});
			if (item.text) setExtras((prev) => [...prev, {
				name: item.name,
				text: item.text
			}].slice(-3));
			onToast(`${file.name} в недавних`);
			const autos = useStudio.getState().data.automations.filter((a) => a.enabled && !a.paused && a.trigger === "upload");
			for (const auto of autos) {
				if (auto.preset === "summary" || auto.preset === "translate") mutate((d) => {
					const row = d.automations.find((x) => x.id === auto.id);
					if (row && item.text) row.prompt = item.text.slice(0, 4e3);
				});
				runAutomation(auto.id);
			}
		} catch {
			onToast("Не удалось прочитать файл");
		}
	}
